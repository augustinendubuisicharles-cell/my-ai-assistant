// Renders the PNG images from the SVG/HTML sources in this folder and writes
// src/assets.js. Run from job_alerts_worker/:  node assets/make_assets.mjs
// (needs Playwright with Chromium; only needed when the artwork changes).
import { chromium } from "playwright";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL(".", import.meta.url));
const browser = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {});

async function shot(file, width, height, out, scale = 1, jpeg = false) {
  const page = await browser.newPage({ viewport: { width, height }, deviceScaleFactor: scale });
  await page.goto(`file://${dir}${file}`);
  await page.waitForLoadState("networkidle");
  const png = await page.screenshot(jpeg ? { type: "jpeg", quality: 88 } : { omitBackground: true });
  writeFileSync(`${dir}${out}`, png);
  await page.close();
  return png;
}

const svgPage = (svg, w, h) => {
  writeFileSync(`${dir}_tmp.html`, `<!doctype html><style>html,body{margin:0;background:transparent}</style>
<img src="${svg}" width="${w}" height="${h}" style="display:block">`);
  return "_tmp.html";
};

const og = await shot("og.html", 1200, 630, "og.jpg", 1, true);
const icon = await shot(svgPage("mark.svg", 180, 180), 180, 180, "icon-180.png");
const fav = await shot(svgPage("mark.svg", 48, 48), 48, 48, "favicon-48.png");
await shot(svgPage("logo.svg", 496, 128), 496, 128, "logo.png", 2);
await browser.close();
await import("node:fs").then((fs) => fs.rmSync(`${dir}_tmp.html`, { force: true }));

const b64 = (b) => Buffer.from(b).toString("base64");
writeFileSync(`${dir}../src/assets.js`, `// Generated by assets/make_assets.mjs -- edit the sources in assets/ instead.
export const MARK_SVG = ${JSON.stringify(readFileSync(`${dir}mark.svg`, "utf8"))};
export const LOGO_SVG = ${JSON.stringify(readFileSync(`${dir}logo.svg`, "utf8"))};
export const OG_JPG = "${b64(og)}";
export const ICON_PNG = "${b64(icon)}";
export const FAVICON_PNG = "${b64(fav)}";
`);
console.log("og.jpg", og.length, "icon", icon.length, "favicon", fav.length);
